"""C3 attribution study: markdown tables from ``c3_attrib.run()`` results (written to data/audit/c3/tables.md)."""
from __future__ import annotations

import math

from .c3_lit import INREPO, LIT
from .c3_stats import fmt_pct

CLS = ("absurd", "tail", "leak", "unansw", "fluency", "neardup", "not_teacher")
NAMES = {"absurd": "absurd", "tail": "tail", "leak": "leak", "unansw": "unanswerable", "fluency": "fluency",
         "neardup": "near-dup (M2–M6)", "not_teacher": "not teacher-acceptable", "not_valid": "not valid"}


def _pp(d: dict, key: str = "d") -> str:
    if d is None or not isinstance(d.get(key), (int, float)) or not math.isfinite(d[key]):
        return "–"
    return f"{100 * d[key]:+.0f} [{100 * d['lo']:+.0f}, {100 * d['hi']:+.0f}]"


def _p(x) -> str:
    if x is None or not isinstance(x, (int, float)) or not math.isfinite(x):
        return "–"
    return f"{x:.3f}" if x >= 0.001 else f"{x:.1e}"


def _sig(d: dict) -> str:
    return "**" if d and isinstance(d.get("lo"), float) and (d["lo"] > 0 or d["hi"] < 0) else ""


def _short(r: dict) -> str:
    return f"{100 * r['p']:.0f}% [{100 * r['lo']:.0f}–{100 * r['hi']:.0f}]" if r["n"] else "–"


def tables(R: dict) -> str:
    L: list[str] = []
    a = L.append
    a("# C3 attribution tables (generated by `python -m vi_math_verified_aug.analysis.c3_attrib`)\n")
    a("All rates: Wilson 95% CI. Paired RD: Newcombe (1998) method-10 CI, exact McNemar p, Holm within each "
      "contrast family (7 classes). Seed-level effects: cluster bootstrap over seeds (4,000) and cluster permutation "
      "(10,000). Judge: Opus 5.5 `validity_judge.v2` unless marked Sonnet (`validity_judge.v3`). ** = CI excludes 0.\n")

    # T1
    a("## T1. Error rates per set (Opus v2)\n")
    a("| set | " + " | ".join(NAMES[c] for c in CLS) + " |")
    a("|---|" + "---|" * len(CLS))
    sr = R["seed_rates"]
    a("| **60 seed texts (no transformation)** | " + " | ".join(
        (_short(sr[c]) if c in sr else "n/a") for c in CLS) + " |")
    for name, rr in R["rates"].items():
        a(f"| {name} | " + " | ".join(_short(rr[c]) for c in CLS) + " |")
    for name, rr in R["survivor_rates"].items():
        a(f"| {name} | " + " | ".join(_short(rr[c]) for c in CLS) + " |")
    a("")

    # T2 matrix
    a("## T2. Attribution matrix — effect of each factor with the others held fixed (pp, 95% CI)\n")
    a("| class | seed PAF in E / R1 / N | operator: max excess over M1 (R1; N) | renderer: max paired RD | "
      "generator model (G1, vs Haiku) | prompt (G2, vs v1) | approach: Y − N same slots (E / R1 / R2) |")
    a("|---|---|---|---|---|---|---|")
    for c in CLS:
        m = R["matrix"][c]
        paf = " / ".join(
            (f"{100 * m[f'seed_paf_{v}']['paf']:.0f}% [{100 * m[f'seed_paf_{v}']['lo']:.0f}, {100 * m[f'seed_paf_{v}']['hi']:.0f}]"
             if f"seed_paf_{v}" in m and math.isfinite(m[f"seed_paf_{v}"]["paf"]) else "–") for v in ("E", "R1", "N"))
        ops = "; ".join((f"{m[f'op_max_{v}']['op']} {_pp(m[f'op_max_{v}'])}{_sig(m[f'op_max_{v}'])}"
                         if f"op_max_{v}" in m else "–") for v in ("R1", "N"))
        rn = m["renderer_max"]
        ren = f"{rn['pair'].replace('_vs_', '→')} {_pp(rn)}{_sig(rn)} (p={_p(rn['p_mcnemar'])})"
        gen = (f"{m['generator_max']['level']} {_pp(m['generator_max'])}{_sig(m['generator_max'])} "
               f"(omnibus p={_p(m['generator_omnibus_p'])})") if "generator_max" in m else "–"
        pro = (f"{m['prompt_max']['level']} {_pp(m['prompt_max'])}{_sig(m['prompt_max'])} "
               f"(omnibus p={_p(m['prompt_omnibus_p'])})") if "prompt_max" in m else "–"
        app = " / ".join(f"{_pp(m[f'approach_{v}'])}{_sig(m[f'approach_{v}'])}" for v in ("E", "R1", "R2"))
        a(f"| {NAMES[c]} | {paf} | {ops} | {ren} | {gen} | {pro} | {app} |")
    a("")

    # T3 seed
    a("## T3. (i) Seed text: P(item has defect | seed has the same defect) vs | seed clean\n")
    a("| variant | class | seed defective: item rate | seed clean: item rate | RD (cluster boot) | perm p | PAF | exposed seeds |")
    a("|---|---|---|---|---|---|---|---|")
    for v, res in R["seed"].items():
        for c, r in res.items():
            if "rd" not in r:
                continue
            paf = r["paf"]
            pf = (f"{100 * paf['paf']:.0f}% [{100 * paf['lo']:.0f}, {100 * paf['hi']:.0f}]"
                  if math.isfinite(paf["paf"]) else "–")
            a(f"| {v} | {NAMES[c]} | {fmt_pct(r['exposed'])} | {fmt_pct(r['unexposed'])} | {_pp(r['rd'])}{_sig(r['rd'])} | "
              f"{_p(r['p_perm'])} | {pf} | {r['n_seeds_exposed']} |")
    a("")

    # T4 operator
    a("## T4a. (ii) Operator: rate by operator (absurd / unanswerable / near-dup / not teacher; n)\n")
    a("| variant | M1 | M2 | M3 | M4 | M5 | M6 |")
    a("|---|---|---|---|---|---|---|")
    for v, bo in R["by_op"].items():
        cells = []
        for op in ("M1", "M2", "M3", "M4", "M5", "M6"):
            if op not in bo:
                cells.append("–")
                continue
            d = bo[op]
            nd = f"{100 * d['neardup']['p']:.0f}%" if "neardup" in d else "n/a"
            cells.append(f"{100 * d['absurd']['p']:.0f}% / {100 * d['unansw']['p']:.0f}% / {nd} / "
                         f"{100 * d['not_teacher']['p']:.0f}% (n={d['absurd']['n']})")
        a(f"| {v} | " + " | ".join(cells) + " |")
    a("")
    a("## T4b. (ii) Operator vs M1 inside one pipeline (RD pp, cluster bootstrap over seeds)\n")
    a("| variant | op | absurd | unanswerable | fluency | tail | not teacher |")
    a("|---|---|---|---|---|---|---|")
    for v, ov in R["op_vs_m1"].items():
        for op, d in ov.items():
            a(f"| {v} | {op} | " + " | ".join(f"{_pp(d[c])}{_sig(d[c])}" for c in ("absurd", "unansw", "fluency", "tail", "not_teacher")) + " |")
    a("")
    a("## T4c. (ii) Same operator request, Y renderer − N on the same slot (paired RD pp; McNemar p)\n")
    a("| Y variant | op | n pairs | absurd | unanswerable | near-dup | not teacher |")
    a("|---|---|---|---|---|---|---|")
    for v, by in R["y_minus_n_by_op"].items():
        for op, d in by.items():
            cells = []
            for c in ("absurd", "unansw", "neardup", "not_teacher"):
                cells.append(f"{_pp(d[c])}{_sig(d[c])} (p={_p(d[c].get('p_mcnemar'))})" if d[c].get("n") else "–")
            a(f"| {v} | {op} | {d['n_pairs']} | " + " | ".join(cells) + " |")
    a("")
    of = R["operator_fix"]
    a("## T4d. (ii) G3 operators → G4 fixed operators, same slots, same renderer (editor.v3)\n")
    a(f"Slots: {of['n_slots']}; tag-passing items produced: G3 {of['produced_g3']}, G4-E {of['produced_g4']}.\n")
    a("| scope | slots | yield G3 → G4 | per-slot defective-item RD: absurd | tail | unanswerable | not teacher | "
      "per produced item, absurd G3 → G4 | tail G3 → G4 | not teacher G3 → G4 | same-program label agreement |")
    a("|---|---|---|---|---|---|---|---|---|---|---|")
    for scope in ("all", "changed ops M3/M4/M6", "unchanged ops M1/M2/M5"):
        r = of[scope]
        pi3, pi4 = r["per_item_g3"], r["per_item_g4"]
        a(f"| {scope} | {r['n_slots']} | {100 * r['yield_g3']:.0f}% → {100 * r['yield_g4']:.0f}% | {_pp(r['absurd'])}{_sig(r['absurd'])} | "
          f"{_pp(r['tail'])}{_sig(r['tail'])} | {_pp(r['unansw'])}{_sig(r['unansw'])} | {_pp(r['not_teacher'])}{_sig(r['not_teacher'])} | "
          f"{_short(pi3['absurd'])} → {_short(pi4['absurd'])} | {_short(pi3['tail'])} → {_short(pi4['tail'])} | "
          f"{_short(pi3['not_teacher'])} → {_short(pi4['not_teacher'])} | "
          f"{r['same_program_label_agreement'] if r['same_program_label_agreement'] is not None else '–'} (n={r['same_program_slots']}) |")
    a("")

    # T5 renderer
    for key, title in (("renderer", "Opus v2"), ("renderer_sonnet", "Sonnet v3 (judge robustness)")):
        a(f"## T5. (iii) Renderer on the same mutated programs — {title} (paired RD pp = second − first)\n")
        a("| pair | n | " + " | ".join(NAMES[c] for c in CLS) + " |")
        a("|---|---|" + "---|" * len(CLS))
        for pair, d in R[key].items():
            a(f"| {pair.replace('_vs_', ' → ')} | {d['n_pairs']} | " + " | ".join(
                f"{_pp(d[c])}{_sig(d[c])} (p={_p(d[c].get('p_mcnemar'))})" for c in CLS) + " |")
        a("")
    g = R["g1_editor"]
    a(f"## T5b. (iii) Editor model on the same G1 edit lists (n = {g['n_blocks']} paired renders)\n")
    a("| model | " + " | ".join(NAMES[c] for c in CLS) + " |")
    a("|---|" + "---|" * len(CLS))
    for l in g["levels"]:
        a(f"| {l} | " + " | ".join(_short(g["rates"][l][c]) for c in CLS) + " |")
    a("| omnibus Cochran-Q perm p | " + " | ".join(_p((g["omnibus"][c] or {}).get("p_perm")) for c in CLS) + " |")
    a("")

    # T6 generator / prompt
    for key, title in (("g1_native", "(iv) Generator model, native generation (G1, 30 paired seeds, prompt native_v1)"),
                       ("g2_prompt", "Prompt, native generation (G2, Haiku 5.5, 40 paired seeds)")):
        g = R[key]
        a(f"## T6. {title}\n")
        a("| level | " + " | ".join(NAMES[c] for c in CLS) + " |")
        a("|---|" + "---|" * len(CLS))
        for l in g["levels"]:
            a(f"| {l} | " + " | ".join(_short(g["rates"][l][c]) for c in CLS) + " |")
        a("| omnibus Cochran-Q perm p | " + " | ".join(_p((g["omnibus"][c] or {}).get("p_perm")) for c in CLS) + " |")
        for l in g["levels"][1:]:
            a(f"| RD {l} − {g['levels'][0]} (Holm p) | " + " | ".join(
                f"{_pp(g['vs_ref'][c][l])} ({_p(g['vs_ref'][c][l].get('p_holm'))})" for c in CLS) + " |")
        a("")

    # T7 approach
    for key, title in (("approach", "tag-passing, Opus v2"), ("approach_survivors", "Y survivors only (after cycle + gates), Opus v2"),
                       ("approach_sonnet", "tag-passing, Sonnet v3")):
        a(f"## T7. Approach residual: Y − N on the same slots ({title})\n")
        a("| pair | n | " + " | ".join(NAMES[c] for c in CLS) + " |")
        a("|---|---|" + "---|" * len(CLS))
        for pair, d in R[key].items():
            a(f"| {pair.replace('_vs_N', ' − N')} | {d['n_pairs']} | " + " | ".join(
                f"{_pp(d[c])}{_sig(d[c])} (p={_p(d[c].get('p_mcnemar'))})" for c in CLS) + " |")
        a("")

    # T8 absurd causes
    a("## T8. NL-ABSURD items coded by cause (reading; `analysis/c3_absurd.py`)\n")
    a("| variant | absurd / items | primary cause counts | any-cause counts | primary factor | absurd if LOC-only items removed |")
    a("|---|---|---|---|---|---|")
    for v, s in R["absurd_causes"].items():
        fmt = lambda d: ", ".join(f"{k} {n}" for k, n in sorted(d.items(), key=lambda kv: -kv[1]))  # noqa: E731
        a(f"| {v} | {s['n_absurd']}/{s['n_items']} | {fmt(s['primary'])} | {fmt(s['any'])} | {fmt(s['factor_primary'])} | "
          f"{s['absurd_without_loc_only']}/{s['n_items']} |")
    a("")

    # T8b localization
    a("## T8b. Localization (USD → đồng ×1.000, imperial relabel) inside R1/R2: localized vs not (Opus v2)\n")
    a("| variant | localized? | absurd | not teacher | fluency |")
    a("|---|---|---|---|---|")
    for v, d in R.get("localized_split", {}).items():
        for flag, rr in d.items():
            a(f"| {v} | {flag} | {fmt_pct(rr['absurd'])} | {fmt_pct(rr['not_teacher'])} | {fmt_pct(rr['fluency'])} |")
    a("")
    if R.get("r1b"):
        a("## T8c. R1b re-render (fluency.v2: 1 USD = 10.000 đồng, no feet/ounce relabel), same slots — "
          "paired RD pp = second − first (Opus v2, judged by D5)\n")
        a("| pair | n | " + " | ".join(NAMES[c] for c in CLS) + " |")
        a("|---|---|" + "---|" * len(CLS))
        for pair, d in R["r1b"].items():
            a(f"| {pair.replace('_vs_', ' → ').replace('_minus_N', ' − N')} | {d['n_pairs']} | " + " | ".join(
                f"{_pp(d[c])}{_sig(d[c])} (p={_p(d[c].get('p_mcnemar'))})" for c in CLS) + " |")
        a("\n`R1b − N`: first = N, second = R1b.\n")

    # T9 literature
    a("## T9a. Operator-matched literature baseline: GSM-Plus human pass rate vs our well-posed ∧ op-applied rate\n")
    a("| op | GSM-Plus perturbation | GSM-Plus pass (GPT-4, human-checked) | G3 | E | R1 | R2 | N |")
    a("|---|---|---|---|---|---|---|---|")
    for op, row in R["lit_ops"].items():
        a(f"| {op} | {row['gsmplus_type']} | {row['gsmplus_pass']:.2f}% | " + " | ".join(
            (_short(row[v]) + ("" if row[v]["lit_inside_ci"] else " ≠")) if v in row else "–" for v in ("G3", "E", "R1", "R2", "N")) + " |")
    a("\n≠ = the literature value lies outside our Wilson CI.\n")
    a("## T9b. Answer faithfulness vs MathCAMPS cycle consistency (12.2% unfaithful before, 97.7% faithful after)\n")
    a("| variant | unfaithful, all tag-passing | faithful, cycle-passed | cycle rejected share |")
    a("|---|---|---|---|")
    for v, d in R["cycle_faithfulness"].items():
        a(f"| {v} | {fmt_pct(d['all_tag_passing_unfaithful'])} | {fmt_pct(d['cycle_passed_faithful'])} | {fmt_pct(d['cycle_rejected_share'])} |")
    a("")
    a("## T9c. Literature baselines (exact numbers as reported)\n")
    a("| source | generator → checker | measure | value | maps to | comparability |")
    a("|---|---|---|---|---|---|")
    for s in LIT:
        for r in s["rows"]:
            val = "not reported" if r["value"] is None else f"{r['value']} {r['unit']}"
            a(f"| [{s['id']}]({s['url']}) — {s['cite']} | {s['generator']} → {s['checker']} | {r['what']} | {val} | "
              f"{r['ours']} | {s['comparable']} |")
    a("")
    a("## T9d. In-repo measured baselines (same taxonomy, read per PROTOCOL.md)\n")
    for s in INREPO:
        a(f"- **{s['id']}** ({s['src']}): " + "; ".join(f"{k} {v}" for k, v in s["rates"].items()))
    a("")
    return "\n".join(L)
